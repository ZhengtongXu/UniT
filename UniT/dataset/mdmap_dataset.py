"""
MD-Map Dataset for AlignTac Training

Loads GelSight tactile images and corresponding MD-Map ground truth
for training the Memory-Augmented VQ-VAE.

Data Organization:
    data_root/
    ├── replay_buffer.zarr/          # Tactile images (from UniT format)
    │   └── data/
    │       └── tactile_image/       # (N, H, W, 3) uint8
    └── mdmap_gt/                    # MD-Map GT (generated by generate_mdmap_gt.py)
        ├── episode_001/
        │   └── mdmap_gt.npz         # (T, 240, 320, 3) float32
        ├── episode_002/
        │   └── mdmap_gt.npz
        └── ...

Author: Claude Code
Date: 2025-12-17
"""

import os
import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader
from pathlib import Path
from typing import Dict, Optional, List
import zarr


class MDMapDataset(Dataset):
    """
    MD-Map Dataset for AlignTac Training

    Loads paired tactile images and MD-Map GT for dual-objective learning.
    """

    def __init__(
        self,
        data_root: str,
        mdmap_root: str,
        image_size = (128, 160),  # Can be int (square) or tuple (H, W)
        mdmap_size: tuple = (240, 320),
        resized_mdmap_shape: tuple = (128, 160),
        split: str = 'train',
        val_ratio: float = 0.1,
        normalize_image: bool = True,
        augment: bool = True,
    ):
        """
        Initialize MD-Map Dataset

        Args:
            data_root: Path to tactile images (zarr format, UniT-style)
            mdmap_root: Path to MD-Map GT directory
            image_size: Resize tactile images to this size. Can be:
                       - int: square resize (e.g., 128 -> 128x128)
                       - tuple: (H, W) resize (e.g., (128, 160) -> 128x160)
            mdmap_size: MD-Map GT original resolution (H, W) - usually (240, 320)
            resized_mdmap_shape: Resize MD-Map to this shape during loading (H, W)
            split: 'train', 'val', or 'all'
            val_ratio: Validation split ratio
            normalize_image: Normalize images to [-1, 1]
            augment: Apply data augmentation (only for train split)
        """
        super().__init__()

        self.data_root = Path(data_root)
        self.mdmap_root = Path(mdmap_root)
        # Convert image_size to tuple if it's an int
        if isinstance(image_size, int):
            self.image_size = (image_size, image_size)
        elif isinstance(image_size, (list, tuple)):
            self.image_size = tuple(image_size)
        else:
            raise TypeError(f"image_size must be int or tuple, got {type(image_size)}")
        self.mdmap_size = mdmap_size  # Original GT resolution
        self.resized_mdmap_shape = resized_mdmap_shape  # Target training resolution
        self.split = split
        self.val_ratio = val_ratio
        self.normalize_image = normalize_image
        self.augment = augment and (split == 'train')

        # Load data
        self._load_tactile_images()
        self._load_mdmap_gt()
        self._build_valid_pairs()
        self._split_data()

        print(f"[MDMapDataset] Loaded {len(self.indices)} samples for {split}")

    def _load_tactile_images(self):
        """Load tactile images from zarr"""
        zarr_path = self.data_root / 'replay_buffer.zarr'
        if not zarr_path.exists():
            raise FileNotFoundError(f"Zarr file not found: {zarr_path}")

        root = zarr.open(str(zarr_path), mode='r')
        self.images = root['data']['tactile_image']  # (N, H, W, 3)
        self.total_frames = len(self.images)

        # Load episode boundaries if available
        if 'meta' in root and 'episode_ends' in root['meta']:
            self.episode_ends = root['meta']['episode_ends'][:]
        else:
            # Assume single episode
            self.episode_ends = np.array([self.total_frames])

        print(f"  Loaded {self.total_frames} tactile images")
        print(f"  {len(self.episode_ends)} episodes")

    def _load_mdmap_gt(self):
        """Load MD-Map GT from npz files"""
        # Find all mdmap_gt.npz files
        print(f"  [DEBUG] Searching for MD-Maps in: {self.mdmap_root}")
        print(f"  [DEBUG] mdmap_root exists: {self.mdmap_root.exists()}")
        print(f"  [DEBUG] mdmap_root is_dir: {self.mdmap_root.is_dir()}")
        mdmap_files = sorted(self.mdmap_root.rglob("mdmap_gt.npz"))

        if len(mdmap_files) == 0:
            raise FileNotFoundError(f"No mdmap_gt.npz files found in {self.mdmap_root}")

        print(f"  Found {len(mdmap_files)} MD-Map GT files")

        # Load all MD-Maps into memory (or keep file paths for lazy loading)
        # For simplicity, we'll concatenate all episodes
        self.mdmaps = []
        self.mdmap_episode_ends = [0]

        for npz_file in mdmap_files:
            data = np.load(npz_file)
            md_map = data['md_map']  # (T, H, W, 3)
            self.mdmaps.append(md_map)
            self.mdmap_episode_ends.append(self.mdmap_episode_ends[-1] + len(md_map))

        # Concatenate all episodes
        self.mdmaps_concat = np.concatenate(self.mdmaps, axis=0)  # (N_total, H, W, 3)
        self.total_mdmap_frames = len(self.mdmaps_concat)

        print(f"  Total MD-Map frames: {self.total_mdmap_frames}")
        print(f"  [DEBUG] Loaded {len(self.mdmaps)} MD-Map episodes")
        print(f"  [DEBUG] mdmaps_concat.shape = {self.mdmaps_concat.shape}")

    def _build_valid_pairs(self):
        """Build valid image-mdmap pairs"""
        # Ensure number of frames match
        if self.total_frames != self.total_mdmap_frames:
            print(f"Warning: Frame count mismatch! Images: {self.total_frames}, MD-Maps: {self.total_mdmap_frames}")
            # Use minimum
            n_frames = min(self.total_frames, self.total_mdmap_frames)
        else:
            n_frames = self.total_frames

        # All frames are valid
        self.all_indices = np.arange(n_frames)

    def _split_data(self):
        """
        Split data into train/val BY EPISODE (not by frame)

        CRITICAL: We must split at episode boundaries, not randomly shuffle frames.
        Memory module requires consecutive frames from the same episode.
        """
        n_episodes = len(self.episode_ends)
        n_val_frames = int(len(self.all_indices) * self.val_ratio)

        # Fixed random seed for reproducibility
        rng = np.random.RandomState(42)
        episode_order = rng.permutation(n_episodes)

        if self.split == 'all':
            self.indices = self.all_indices
            return

        # Collect episodes for train vs val
        train_episodes = []
        val_episodes = []
        val_frames_collected = 0

        for ep_idx in episode_order:
            # Get frame count for this episode
            start = 0 if ep_idx == 0 else self.episode_ends[ep_idx - 1]
            end = self.episode_ends[ep_idx]
            n_frames = end - start

            # Assign whole episodes to val first until we have enough val frames
            if val_frames_collected < n_val_frames:
                val_episodes.append(ep_idx)
                val_frames_collected += n_frames
            else:
                train_episodes.append(ep_idx)

        # Now collect the actual frame indices for the selected episodes
        # AND compute NEW episode_ends that are relative to the subset
        if self.split == 'train':
            self.indices = []
            self.local_episode_ends = []
            cumulative_frames = 0

            for ep_idx in sorted(train_episodes):  # Sort to maintain order
                start = 0 if ep_idx == 0 else self.episode_ends[ep_idx - 1]
                end = self.episode_ends[ep_idx]
                episode_frames = np.arange(start, end)
                self.indices.extend(episode_frames)
                cumulative_frames += len(episode_frames)
                self.local_episode_ends.append(cumulative_frames)

            self.indices = np.array(self.indices)
            self.local_episode_ends = np.array(self.local_episode_ends)

        elif self.split == 'val':
            self.indices = []
            self.local_episode_ends = []
            cumulative_frames = 0

            for ep_idx in sorted(val_episodes):  # Sort to maintain order
                start = 0 if ep_idx == 0 else self.episode_ends[ep_idx - 1]
                end = self.episode_ends[ep_idx]
                episode_frames = np.arange(start, end)
                self.indices.extend(episode_frames)
                cumulative_frames += len(episode_frames)
                self.local_episode_ends.append(cumulative_frames)

            self.indices = np.array(self.indices)
            self.local_episode_ends = np.array(self.local_episode_ends)

        print(f"  [DEBUG] Split='{self.split}': {len(self.indices)} frames")
        if len(self.indices) > 0:
            print(f"  [DEBUG] Index range: [{self.indices.min()}:{self.indices.max()}]")
            print(f"  [DEBUG] mdmaps_concat size: {len(self.mdmaps_concat)}")
            print(f"  [DEBUG] Max safe index: {len(self.mdmaps_concat) - 1}")

    def _augment_pair(self, image, mdmap):
        """Apply data augmentation to image and MD-Map pair"""
        # Horizontal flip
        if np.random.rand() > 0.5:
            image = np.fliplr(image).copy()
            mdmap = np.fliplr(mdmap).copy()
            mdmap[:, :, 0] = -mdmap[:, :, 0]  # Flip dx channel

        # Vertical flip
        if np.random.rand() > 0.5:
            image = np.flipud(image).copy()
            mdmap = np.flipud(mdmap).copy()
            mdmap[:, :, 1] = -mdmap[:, :, 1]  # Flip dy channel

        # Color jitter (only for image)
        if np.random.rand() > 0.5:
            brightness = 0.8 + np.random.rand() * 0.4  # [0.8, 1.2]
            image = np.clip(image * brightness, 0, 255).astype(np.uint8)

        return image, mdmap

    def __len__(self):
        return len(self.indices)

    def _get_episode_id(self, frame_idx):
        """
        Get episode ID for a given frame index

        Args:
            frame_idx: Global frame index

        Returns:
            episode_id: Which episode this frame belongs to
        """
        for ep_idx, end in enumerate(self.episode_ends):
            start = 0 if ep_idx == 0 else self.episode_ends[ep_idx - 1]
            if start <= frame_idx < end:
                return ep_idx
        return -1  # Should never happen

    def __getitem__(self, idx):
        """
        Get a single sample

        Returns:
            dict with:
                - image: (3, H, W) tensor - Tactile image
                - md_map: (3, H, W) tensor - MD-Map GT
                - episode_id: int - Which episode this frame belongs to
                - frame_idx: int - Global frame index (for debugging)
        """
        frame_idx = self.indices[idx]

        # Get episode ID
        episode_id = self._get_episode_id(frame_idx)

        # Load tactile image
        image = np.array(self.images[frame_idx])  # (H, W, 3) uint8

        # Load MD-Map
        mdmap = self.mdmaps_concat[frame_idx]  # (H, W, 3) float32

        # Resize image if needed
        # Note: self.image_size is (H, W), but PIL.resize expects (W, H)
        if image.shape[0] != self.image_size[0] or image.shape[1] != self.image_size[1]:
            from PIL import Image as PILImage
            pil_img = PILImage.fromarray(image)
            pil_img = pil_img.resize((self.image_size[1], self.image_size[0]), PILImage.BILINEAR)
            image = np.array(pil_img)

        # Resize MD-Map to training resolution (following UniT's pattern)
        # GT is at original resolution (240x320), we resize to resized_mdmap_shape (128x160)
        if mdmap.shape[0] != self.resized_mdmap_shape[0] or mdmap.shape[1] != self.resized_mdmap_shape[1]:
            from PIL import Image as PILImage
            # Resize each channel separately to preserve float values
            mdmap_resized = np.zeros((*self.resized_mdmap_shape, 3), dtype=np.float32)
            for c in range(3):
                pil_ch = PILImage.fromarray(mdmap[:, :, c])
                pil_ch_resized = pil_ch.resize(
                    (self.resized_mdmap_shape[1], self.resized_mdmap_shape[0]),  # (W, H)
                    PILImage.BILINEAR
                )
                mdmap_resized[:, :, c] = np.array(pil_ch_resized)
            mdmap = mdmap_resized

        # Data augmentation
        if self.augment:
            image, mdmap = self._augment_pair(image, mdmap)

        # Convert to tensor
        # Keep in (H, W, 3) format - get_input() will handle the permute to (3, H, W)
        image_tensor = torch.from_numpy(image).float()
        if self.normalize_image:
            image_tensor = image_tensor / 127.5 - 1.0  # [-1, 1]
        else:
            image_tensor = image_tensor / 255.0  # [0, 1]

        # MD-Map: Keep in (H, W, 3) format
        mdmap_tensor = torch.from_numpy(mdmap).float()

        return {
            'image': image_tensor,
            'md_map': mdmap_tensor,
            'episode_id': episode_id,
            'frame_idx': frame_idx,
        }


class MDMapDataModule:
    """
    Data module for easy integration with training scripts
    """

    def __init__(
        self,
        data_root: str,
        mdmap_root: str,
        batch_size: int = 32,
        num_workers: int = 8,
        image_size = (128, 160),  # Can be int (square) or tuple (H, W)
        mdmap_size: tuple = (240, 320),
        resized_mdmap_shape: tuple = (128, 160),
        val_ratio: float = 0.1,
        augment: bool = True,
    ):
        self.data_root = data_root
        self.mdmap_root = mdmap_root
        self.batch_size = batch_size
        self.num_workers = num_workers
        # Normalize image_size to tuple
        if isinstance(image_size, int):
            self.image_size = (image_size, image_size)
        else:
            self.image_size = image_size
        self.mdmap_size = mdmap_size
        self.resized_mdmap_shape = resized_mdmap_shape
        self.val_ratio = val_ratio
        self.augment = augment
        self.has_prepared_data = False
        self.has_setup_fit = False
        self.has_setup_validate = False
        self.has_setup_test = False

    def prepare_data(self):
        """Prepare data (called only on 1 GPU/TPU in distributed training)"""
        # Nothing to do here - data is already prepared
        self.has_prepared_data = True

    def on_save_checkpoint(self, checkpoint):
        """Called when saving checkpoints"""
        pass

    def on_load_checkpoint(self, checkpoint):
        """Called when loading checkpoints"""
        pass

    def setup(self, stage=None):
        """Create datasets"""
        if stage == 'fit' or stage is None:
            self.has_setup_fit = True
        if stage == 'validate' or stage is None:
            self.has_setup_validate = True
        if stage == 'test' or stage is None:
            self.has_setup_test = True
        self.train_dataset = MDMapDataset(
            data_root=self.data_root,
            mdmap_root=self.mdmap_root,
            image_size=self.image_size,
            mdmap_size=self.mdmap_size,
            resized_mdmap_shape=self.resized_mdmap_shape,
            split='train',
            val_ratio=self.val_ratio,
            augment=self.augment,
        )

        self.val_dataset = MDMapDataset(
            data_root=self.data_root,
            mdmap_root=self.mdmap_root,
            image_size=self.image_size,
            mdmap_size=self.mdmap_size,
            resized_mdmap_shape=self.resized_mdmap_shape,
            split='val',
            val_ratio=self.val_ratio,
            augment=False,
        )

    def train_dataloader(self):
        from .episode_sampler import EpisodeSequentialSampler

        # Use episode-aware sampler to maintain temporal continuity
        # Use local_episode_ends if available (after train/val split), otherwise use global episode_ends
        episode_ends_to_use = getattr(self.train_dataset, 'local_episode_ends', self.train_dataset.episode_ends)

        sampler = EpisodeSequentialSampler(
            episode_ends=episode_ends_to_use,
            batch_size=self.batch_size,
            shuffle_episodes=True,  # Shuffle episodes, but keep frames sequential within episodes
            drop_last=False,  # Keep all data
        )

        return DataLoader(
            self.train_dataset,
            batch_sampler=sampler,  # Use batch_sampler instead of batch_size + shuffle
            num_workers=self.num_workers,
            pin_memory=True,
        )

    def val_dataloader(self):
        return DataLoader(
            self.val_dataset,
            batch_size=self.batch_size,
            shuffle=False,
            num_workers=self.num_workers,
            pin_memory=True,
            drop_last=False,
        )


